# --- git hygiene ------------------------------------------------------------
# These rules go in .git/info/exclude, NEVER in .gitignore.
#
# .gitignore is a TRACKED file. Appending to it means the first command run
# against a borrowed repository modifies a file that repository's owner owns,
# which is exactly what the zero-footprint guarantee promises will not happen --
# and if anyone later commits with `-a` or `add -A`, that edit ships to them
# inside unrelated work. .git/info/exclude does the same job, is local, and is
# invisible to everyone else.
#
# The RULES themselves are unchanged, deliberately. An earlier version of this
# fix also excluded the whole of `.omni/` in repositories that do not yet track
# it, on the reasoning that in a borrowed tree those files are ours. That was
# wrong twice over, and both were found by review rather than by these tests:
#
#   - `deploy/nightshift-state-backup.sh` snapshots the org's state with
#     `git add -- .omni docs`, which honours this file exactly as it honoured
#     `.gitignore`. Excluding `.omni/` made the 30-minute backup capture
#     NOTHING, silently, in precisely the borrowed repositories it exists for.
#   - The choice was made once, at init, on a repository that by definition has
#     nothing yet, and never re-evaluated -- so a new project could never begin
#     tracking its own charters and decisions.
#
# Keeping `.omni/` out of a customer's tree is a real problem and it is #400's:
# the state belongs OUTSIDE the borrowed repository, not hidden inside it. An
# ignore rule cannot solve it without breaking the backup path that reads those
# same files.
EXCLUDE=.git/info/exclude
mkdir -p "$(dirname "$EXCLUDE")"
[ -f "$EXCLUDE" ] || : > "$EXCLUDE"

