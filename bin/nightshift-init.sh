#!/usr/bin/env bash
# Bootstrap a repo for the Omnigent crew setup.
# Usage:  ~/.nightshift/bin/nightshift-init.sh [repo-path]
# Idempotent: existing files are left alone.

set -euo pipefail

# Resolve the bundle root BEFORE any cd — $0 is relative for relative
# invocations and silently points nowhere after cd'ing into the repo.
BUNDLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

REPO="${1:-$PWD}"
cd "$REPO"

if [ ! -d .git ]; then
  echo "error: $REPO is not a git repo (agents need worktrees and PRs)" >&2
  exit 1
fi

# Audit C3: this runs against a TARGET repository, which can track `.omni`,
# `docs/...` or any file below them as a symlink into the operator's home
# (`.omni/STATUS.md -> ~/.bashrc`). Every directory written into must be a
# real directory owned by this user, and every file is created exclusively
# (noclobber: O_EXCL, so even a dangling link refuses) by `new_file`, which
# also refuses a link by name. To keep state elsewhere, configure that path
# explicitly rather than linking it in.
STATE_DIRS=".omni/handoffs .omni/sync .omni/transcripts .omni/incidents
  .omni/leases .omni/reports docs/architecture docs/decisions docs/specs
  docs/prd docs/design docs/tests docs/releases .worktrees"
set -o noclobber

require_real_dirs() {
  local d part path
  for d in $STATE_DIRS; do
    path=""
    for part in ${d//\// }; do
      path="${path:+$path/}$part"
      if [ -L "$path" ] || { [ -e "$path" ] && { [ ! -d "$path" ] || [ ! -O "$path" ]; }; }; then
        echo "error: $REPO/$path is a symlink or not a directory owned by you;" \
             "refusing to write state through it" >&2
        exit 1
      fi
    done
  done
}

new_file() {
  if [ -L "$1" ]; then
    echo "error: $REPO/$1 is a symlink; refusing to write through it" >&2
    exit 1
  fi
  cat > "$1"
}

require_real_dirs
# shellcheck disable=SC2086  # STATE_DIRS is a fixed, space-free list
mkdir -p $STATE_DIRS
require_real_dirs

